"""Project verified, retained evidence into the frontend without running any models.

Run from any directory. --check compares every generated byte and detects stale or
unexpected output. Evidence timestamps are preserved; export adds no current time.
"""

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RECORDINGS = ROOT / "core" / "examples" / "recordings"
BUNDLE = RECORDINGS / "container-benchmarks-2026-10-17"
SOURCE = RECORDINGS / "advisor-live-2026-10-17"
OUTPUT = ROOT / "web" / "public" / "benchmarks"
SOURCE_COMMIT = "ecd976d2d7d7118179cd0260d2add4110b014c49"


def contents(path):
    # These committed text artifacts have LF publication hashes. Git's Windows
    # working-tree conversion must not change published/downloaded bytes.
    return path.read_bytes().replace(b"\r\n", b"\n")


def digest(data):
    return hashlib.sha256(data).hexdigest()


def read(path):
    return json.loads(contents(path))


def safe_path(root, relative):
    path = root / relative
    if Path(relative).is_absolute() or ".." in Path(relative).parts:
        raise ValueError(f"Unsafe manifest path: {relative}")
    if not path.resolve().is_relative_to(root.resolve()):
        raise ValueError(f"Manifest escapes evidence directory: {relative}")
    return path


def verify(root, relative, sha, size=None):
    data = contents(safe_path(root, relative))
    if digest(data) != sha or (size is not None and len(data) != size):
        raise ValueError(f"Evidence hash/size mismatch: {root.name}/{relative}")
    return data


def latency(value):
    return {
        "count": value["count"],
        "minMs": value["min_ms"],
        "medianMs": value["median_ms"],
        "maxMs": value["max_ms"],
    }


def project_trial(trial):
    p = trial["projection"]
    return {
        "trial": trial["trial"],
        "cold": trial["worker_cold"],
        "elapsedMs": trial["end_to_end_elapsed_ms"],
        "rawChoice": p["raw_choice"],
        "acceptedChoice": p["accepted_choice"],
        "disposition": p["disposition"],
        "reasons": p["reasons"],
        "scores": trial["result"]["output"]["decision"]["scores"],
        "selectedEntailment": p["selected_entailment"],
        "margin": p["entailment_margin"],
        "minimumEntailment": p["minimum_entailment"],
        "minimumMargin": p["minimum_margin"],
        "thresholdBasis": p["threshold_basis"],
        "ruleBaseline": p["rule_baseline"],
        "remainingFields": p["remaining_fields"],
        "preboundArguments": p["prebound_arguments"],
        "actionExecuted": p["action_executed"],
        "rawMatch": trial["raw_expected_match"],
        "acceptedMatch": trial["accepted_expected_match"],
    }


def build_output():
    master = read(BUNDLE / "manifest.json")
    source_manifest = read(SOURCE / "manifest.json")
    source_hash = digest(contents(SOURCE / "manifest.json"))
    if master["source_manifest_sha256"] != source_hash:
        raise ValueError("Source manifest hash does not match benchmark bundle")
    output = {"raw/manifest.json": contents(BUNDLE / "manifest.json")}
    for entry in master["files"]:
        data = verify(BUNDLE, entry["path"], entry["sha256"], entry["bytes"])
        # JSON downloads retain full precision and failure records. HTML is
        # available in the source repository rather than duplicated in the UI.
        if entry["path"].endswith((".json", ".jsonl")):
            output[f"raw/{entry['path']}"] = data
    for path, entry in source_manifest["files"].items():
        verify(SOURCE, path, entry["sha256"], entry["bytes"])
    output["raw/source-manifest.json"] = contents(SOURCE / "manifest.json")
    nested_jev = read(BUNDLE / "jev" / "manifest.json")
    if nested_jev["source_manifest_sha256"] != source_hash:
        raise ValueError("JEV manifest does not match hosted source manifest")
    for path, sha in nested_jev["files"].items():
        verify(BUNDLE / "jev", path, sha)
    nested_comms = read(BUNDLE / "cpu" / "comms" / "manifest.json")
    for entry in nested_comms["files"]:
        verify(BUNDLE / "cpu" / "comms", entry["path"], entry["sha256"], entry["bytes"])
    for entry in nested_comms["source_recordings"]:
        verify(SOURCE, entry["path"], entry["sha256"])

    comparison = read(BUNDLE / "jev" / "comparison.json")
    if comparison["source_manifest_sha256"] != source_hash:
        raise ValueError("JEV comparison does not match hosted sources")
    for entry in comparison["source_files"]:
        verify(SOURCE, entry["path"], entry["sha256"])
    provenance = read(BUNDLE / "provenance.json")
    audit = read(BUNDLE / "audit.json")
    spend = read(BUNDLE / "spend.json")
    cpu = read(BUNDLE / "cpu" / "summary.json")
    comms = read(BUNDLE / "cpu" / "comms" / "report.json")
    gpu = read(BUNDLE / "gpu-validation.json")
    preflight = read(BUNDLE / "gpu" / "gpu-preflight-validation-named-volume.json")
    summary = comparison["summary"]
    total = comms["totals"]
    mailbox = comms["mailbox"]
    dense = next(s for s in comms["scenarios"] if s["name"] == "Dense float fallback")
    cases = [
        {
            "id": c["case_id"],
            "category": c["category"],
            "stepId": c["step_id"],
            "field": c["field"],
            "expectedChoice": c["expected_choice"],
            "expectationBasis": c["expectation_basis"],
            "premise": c["text_request"]["premise"],
            "choices": c["text_request"]["choices"],
            "requiresExplanation": c["requires_explanation"],
            "trials": [project_trial(t) for t in c["jev_trials"]],
        }
        for c in comparison["cases"]
    ]
    trials = [t for c in cases for t in c["trials"]]
    labels = {
        "jev/comparison.json": "Full JEV comparison and hosted responses",
        "jev/trials.jsonl": "All JEV trial journal entries",
        "cpu/comms/report.json": "CBOR measurements and timing samples",
        "gpu/gpu-preflight-validation-named-volume.json": "GPU capacity check",
        "gpu-validation.json": "GPU compatibility and validation note",
        "provenance.json": "Measurement provenance",
        "audit.json": "Source integrity audit",
        "spend.json": "Incremental provider budget ledger",
        "manifest.json": "Publication SHA256 inventory",
        "source-manifest.json": "Historical hosted source inventory",
    }
    evidence = {
        "schemaVersion": "canopy.benchmark_evidence/v1",
        "publishedAt": provenance["published_at"],
        "auditedAt": audit["audited_at"],
        "sourceCommit": SOURCE_COMMIT,
        "sourceUrl": "https://github.com/liamstojanovic/buildingBetterCode-monorepo/tree/"
        f"{SOURCE_COMMIT}/core/examples/recordings/{BUNDLE.name}",
        "dates": {
            "cpu": cpu["generated_at"],
            "jev": comparison["evaluated_at"],
            "comms": comms["created_at"],
        },
        "revisions": {
            "cpu": provenance["cpu_source_revision"],
            "gpu": provenance["gpu_source_revision"],
        },
        "sourceManifestSha256": source_hash,
        "advisor": {
            "reports": cpu["advisor"]["reports"],
            "groups": cpu["advisor"]["recommendations"],
            "modelCalls": cpu["advisor"]["model_calls"],
        },
        "jev": {
            "model": comparison["configuration"]["model"],
            "distinctCases": summary["distinct_cases"],
            "trials": summary["jev_trials"],
            "rawMatches": sum(t["rawMatch"] for t in trials),
            "acceptedMatches": sum(t["acceptedMatch"] for t in trials),
            "firstTrialRawMatches": summary["jev_first_trial_raw_expected_matches"],
            "firstTrialAcceptedMatches": summary[
                "jev_first_trial_accepted_expected_matches"
            ],
            "coldMs": summary["jev_cold_end_to_end_ms"],
            "modelLoadMs": summary["jev_model_load_ms"],
            "warm": latency(summary["jev_warm_end_to_end_latency"]),
            "hosted": {
                "calls": summary["hosted_calls"],
                "excludedReused": summary["excluded_hosted_reused_steps"],
                "normalizedMatches": summary["hosted_normalized_expected_matches"],
                "strictMatches": summary["hosted_strict_contract_matches"],
                "latency": latency(summary["hosted_recorded_latency"]),
                "wrongChoices": [
                    {
                        "provider": c["provider"],
                        "model": c["model"],
                        "caseId": c["case_id"],
                        "runLabel": c["run_label"],
                        "choice": c["normalized_choice"],
                        "expected": c["expected_choice"],
                    }
                    for c in comparison["hosted_calls"]
                    if not c["normalized_match"]
                ],
            },
            "cases": cases,
            "limitations": comparison["limitations"],
        },
        "comms": {
            "messages": total["messages"],
            "batches": total["batches"],
            "jsonBytes": total["json_bytes"],
            "singleCborBytes": total["single_cbor_bytes"],
            "batchCborBytes": total["batch_cbor_bytes"],
            "base64Bytes": total["base64_bytes"],
            "bytesSaved": total["bytes_saved"],
            "reductionFraction": total["reduction_fraction"],
            "roundtripVerified": total["roundtrip_verified"],
            "networkCalls": total["network_calls"],
            "timingRepetitions": comms["measurement"]["timing_repetitions"],
            "timings": [
                {
                    "encoding": k,
                    "encodeMs": v["encode_median_ms"],
                    "decodeMs": v["decode_median_ms"],
                }
                for k, v in comms["timings"].items()
            ],
            "mailbox": {
                "delivered": mailbox["delivered"],
                "acknowledged": mailbox["acknowledged"],
                "duplicatesSuppressed": mailbox["duplicate_redeliveries_suppressed"],
                "individualMs": mailbox["individual_delivery_ms"],
                "batchMs": mailbox["batch_delivery_ms"],
                "individualTransactions": mailbox["individual_transactions"],
                "batchTransactions": mailbox["batch_transactions"],
                "scope": mailbox["timing_scope"],
            },
            "denseFallback": {
                "jsonBytes": dense["json_bytes"],
                "cborBytes": dense["cbor_bytes"],
                "selectedBytes": dense["selected_bytes"],
                "selectedEncoding": dense["selected_encoding"],
                "detail": dense["detail"],
            },
            "scope": comms["measurement"]["wire_scope"]
            + " "
            + comms["measurement"]["timing_scope"],
            "limitations": comms["measurement"]["limitations"],
        },
        "gpu": {
            "name": gpu["host_gpu"],
            "totalMiB": preflight["memory_before_model"]["total_mib"],
            "allocatorLimitMiB": preflight["allocator_limit_mib"],
            "peakAllocatedMiB": preflight["memory_after_model_and_cases"][
                "peak_allocated_mib"
            ],
            "peakReservedMiB": preflight["memory_after_model_and_cases"][
                "peak_reserved_mib"
            ],
            "teammate12GbTested": gpu["teammate_4080_12gb_tested"],
            "standardCurrentDockerTested": gpu[
                "standard_current_docker_gpu_compose_tested"
            ],
            "compatibilityOverride": gpu["temporary_local_override"],
            "scope": preflight["memory_measurement_note"],
        },
        "spend": {
            "providerUsd": spend["provider_api_spend_usd"],
            "budgetUsd": spend["authorized_limit_usd"],
            "remainingUsd": spend["remaining_authorized_budget_usd"],
            "historicalHostedUsd": spend["historical_hosted_cost_usd"],
            "energySavingsJ": summary["energy_savings_j"],
            "costSavingsUsd": spend["cost_savings_usd"],
            "scope": spend["scope"],
        },
        "downloads": [
            {
                "label": label,
                "url": f"/benchmarks/raw/{path}",
                "sha256": digest(output[f"raw/{path}"]),
            }
            for path, label in labels.items()
        ],
    }
    output["latest.json"] = (
        json.dumps(evidence, indent=2, allow_nan=False) + "\n"
    ).encode()
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if generated public artifacts are stale",
    )
    args = parser.parse_args()
    output = build_output()
    existing = {
        p.relative_to(OUTPUT).as_posix() for p in OUTPUT.rglob("*") if p.is_file()
    }
    extra = existing - output.keys()
    if extra:
        raise ValueError(
            f"Unexpected benchmark output files; review manually: {sorted(extra)}"
        )
    stale = [
        name
        for name, data in output.items()
        if not (OUTPUT / name).is_file() or contents(OUTPUT / name) != data
    ]
    if args.check:
        if stale:
            raise ValueError(
                f"Stale frontend benchmark evidence: {', '.join(stale)}; rerun this script without --check"
            )
        print(
            f"Verified {len(output)} current frontend benchmark artifacts; no model calls"
        )
        return
    for name, data in output.items():
        target = safe_path(OUTPUT, name)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    print(f"Exported {len(output)} frontend benchmark artifacts; no model calls")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, KeyError, OSError) as error:
        print(f"Benchmark export failed: {error}", file=sys.stderr)
        sys.exit(1)
